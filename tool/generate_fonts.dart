import 'dart:convert';
import 'dart:io';

const String _fontPackage = 'awesome_icons';

String _camelCase(String value) {
  final parts = value.split('-');
  return parts.first + parts.skip(1).map((part) => part[0].toUpperCase() + part.substring(1)).join();
}

String _validIdentifier(String value) {
  if (value == '500px') {
    return 'fiveHundredPx';
  }
  return _camelCase(value);
}

String _iconData(String codePoint, String fontFamily) =>
    "IconData(0x$codePoint, fontFamily: '$fontFamily', fontPackage: '$_fontPackage')";

Never _usage() {
  stderr.writeln(
    'Usage: dart run tool/generate_fonts.dart '
    '<icons.json> <brands.json> <regular.json> <solid.json>',
  );
  exit(64);
}

List<dynamic> _readJsonList(String path) {
  final file = File(path);
  if (!file.existsSync()) {
    stderr.writeln('Config file not found: $path');
    exit(66);
  }
  return jsonDecode(file.readAsStringSync()) as List<dynamic>;
}

void main(List<String> args) {
  if (args.length != 4) {
    _usage();
  }

  final icons = _readJsonList(args[0]);
  final brands = _readJsonList(args[1]).cast<String>().toSet();
  final regular = _readJsonList(args[2]).cast<String>().toSet();
  final solid = _readJsonList(args[3]).cast<String>().toSet();

  final output = StringBuffer()
    ..writeln('library awesome_icons;')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('// THIS FILE IS AUTOMATICALLY GENERATED. DO NOT EDIT.')
    ..writeln()
    ..writeln('const Map<String, IconData> fontAwesomeIcons = {');

  for (final icon in icons.cast<Map<String, dynamic>>()) {
    icon.forEach((iconName, iconUnicode) {
      final codePoint = iconUnicode as String;
      if (brands.contains(iconName)) {
        output.writeln("  'fab-$iconName': ${_iconData(codePoint, 'FontAwesome5Brands')},");
      } else if (regular.contains(iconName) && solid.contains(iconName)) {
        output
          ..writeln("  'far-$iconName': ${_iconData(codePoint, 'FontAwesome5Free')},")
          ..writeln("  'fas-$iconName': ${_iconData(codePoint, 'FontAwesome5FreeSolid')},");
      } else if (regular.contains(iconName)) {
        output.writeln("  'far-$iconName': ${_iconData(codePoint, 'FontAwesome5Free')},");
      } else {
        output.writeln("  'fas-$iconName': ${_iconData(codePoint, 'FontAwesome5FreeSolid')},");
      }
    });
  }

  output
    ..writeln('};')
    ..writeln()
    ..writeln('@staticIconProvider')
    ..writeln('abstract final class FontAwesomeIcons {');

  for (final icon in icons.cast<Map<String, dynamic>>()) {
    icon.forEach((iconName, iconUnicode) {
      final codePoint = iconUnicode as String;
      if (brands.contains(iconName)) {
        output.writeln(
          '  static const IconData ${_validIdentifier(iconName)} = '
          "${_iconData(codePoint, 'FontAwesome5Brands')};",
        );
      } else if (regular.contains(iconName) && solid.contains(iconName)) {
        output
          ..writeln(
            '  static const IconData ${_validIdentifier('solid-$iconName')} = '
            "${_iconData(codePoint, 'FontAwesome5FreeSolid')};",
          )
          ..writeln(
            '  static const IconData ${_validIdentifier(iconName)} = '
            "${_iconData(codePoint, 'FontAwesome5Free')};",
          );
      } else if (regular.contains(iconName)) {
        output.writeln(
          '  static const IconData ${_validIdentifier(iconName)} = '
          "${_iconData(codePoint, 'FontAwesome5Free')};",
        );
      } else {
        output.writeln(
          '  static const IconData ${_validIdentifier(iconName)} = '
          "${_iconData(codePoint, 'FontAwesome5FreeSolid')};",
        );
      }
    });
  }

  output.writeln('}');
  File('lib/awesome_icons.dart').writeAsStringSync(output.toString());
}
